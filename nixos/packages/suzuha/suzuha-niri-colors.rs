use super::{hex, state_home, write};
use crate::theme::Theme;

// Niri watches this optional include and reloads it after each palette change.
pub fn export(theme: &Theme) {
    let accent = hex(theme.accent);
    let border = hex(theme.border);
    let danger = hex(theme.danger);
    let background = hex(theme.background);
    let text = format!(
        r#"// Generated by Suzuha from Amane's current palette. Do not edit.
layout {{
    focus-ring {{
        active-color "{accent}"
        inactive-color "{border}"
        urgent-color "{danger}"
    }}
    border {{
        active-color "{accent}"
        inactive-color "{border}"
        urgent-color "{danger}"
    }}
    tab-indicator {{
        active-color "{accent}"
        inactive-color "{border}"
        urgent-color "{danger}"
    }}
    insert-hint {{ color "{accent}80"; }}
    shadow {{
        color "{background}70"
        inactive-color "{background}54"
    }}
}}
overview {{
    backdrop-color "{background}"
    workspace-shadow {{ color "{background}70"; }}
}}
"#
    );
    write(&format!("{}/niri-colors.kdl", state_home()), &text);
}
